# Объединение клеток с np < 5
combine_cells <- function(nu, p, n) {
  # Объединяем с соседом, если np < 5
  np <- n * p
  while (any(np < 5) && length(nu) > 1) {
    idx <- which(np < 5)[1]
    if (idx == length(nu)) idx2 <- idx - 1 else idx2 <- idx + 1
    # объединяем idx и idx2
    merge_idx <- min(idx, idx2)
    nu[merge_idx]  <- nu[merge_idx] + nu[merge_idx + 1]
    p[merge_idx]   <- p[merge_idx]  + p[merge_idx + 1]
    nu <- nu[-(merge_idx + 1)]
    p  <- p[-(merge_idx + 1)]
    np <- n * p
  }
  list(nu = nu, p = p)
}

