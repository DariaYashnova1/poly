x <- c(0,1,3,0,1,0,1,1,1,1,0,0,1,0,0,2,0,0,4,0,
       0,0,0,0,2,3,1,0,0,6,1,1,2,1,0,0,0,1,4,0,
       2,4,0,0,3,0,2,0,0,1)

n  <- length(x)
al <- 0.05

# ------------------------------------------------------------
# Наблюдаемые частоты
# ------------------------------------------------------------

nu <- c(
  sum(x == 0),
  sum(x == 1),
  sum(x >= 2)
)

ranges <- c(
  "(-Inf,1)",
  "[1,2)",
  "[2,Inf)"
)

# ------------------------------------------------------------
# χ² как функция lambda
# ------------------------------------------------------------

chi_sq <- function(lam){
  
  lam <- lam[1]
  
  if(lam <= 0 || lam >= 1){
    return(Inf)
  }
  
  p <- c(
    dgeom(0, lam),
    dgeom(1, lam),
    1 - pgeom(1, lam)
  )
  
  np <- n * p
  
  sum((nu - np)^2 / np)
}

# ------------------------------------------------------------
# Минимизация χ² с помощью nlm
# ------------------------------------------------------------

start_lambda <- 1 / (mean(x) + 1)

opt <- nlm(
  f = chi_sq,
  p = start_lambda
)

lam_hat <- opt$estimate
X2 <- opt$minimum

# ------------------------------------------------------------
# Теоретические вероятности
# ------------------------------------------------------------

p <- c(
  dgeom(0, lam_hat),
  dgeom(1, lam_hat),
  1 - pgeom(1, lam_hat)
)

np <- n * p

# ------------------------------------------------------------
# Остатки
# ------------------------------------------------------------

res  <- (nu - np) / sqrt(np)
res2 <- res^2

# ------------------------------------------------------------
# Степени свободы
# ------------------------------------------------------------

r  <- length(nu)
df <- r - 1 - 1

# ------------------------------------------------------------
# Критическое значение и p-value
# ------------------------------------------------------------

chi_crit <- qchisq(1 - al, df)

p_value <- pchisq(
  X2,
  df,
  lower.tail = FALSE
)

